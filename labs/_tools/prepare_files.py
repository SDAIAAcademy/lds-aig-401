def workdays(a: date, b: date) -> int:
    """Working days after a, up to and including b (Sunday to Thursday)."""
    n, d = 0, a
    while d < b:
        d += timedelta(days=1)
        if d.weekday() in (6, 0, 1, 2, 3):
            n += 1
    return n


