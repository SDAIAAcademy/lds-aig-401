def write_csv(name: str, head: list[str], rows: list[list]) -> None:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(head)
    w.writerows(rows)
    (OUT / name).write_bytes(buf.getvalue().encode("utf-8"))


def write_md(name: str, text: str) -> None:
    (OUT / name).write_bytes((text.strip() + "\n").encode("utf-8"))


