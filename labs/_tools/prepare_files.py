def risk(l, i):
    return "" if l == "" or i == "" else l * i


def rest_rows(rng: random.Random) -> list[list]:
    rows, n = [], 23
    for unit, funcs in REST_FUNCS.items():
        for f in funcs:
            if "وكيل" in f:
                kind = "وكيل"
            elif any(w in f for w in ("مساعد", "صياغة", "تلخيص", "مولد", "ترجمة")):
                kind = "مساعد توليدي"
            elif "أداة" in f:
                kind = "أداة بناها موظف"
            else:
                kind = "نموذج تنبؤي"
            origin = "بناها موظف" if kind == "أداة بناها موظف" else rng.choice(["مطور داخليًا", "مشترى"])
            stage = "تجريبي" if kind == "وكيل" else rng.choice(["تشغيل", "تشغيل", "تشغيل", "تجريبي"])
            affects = "نعم" if any(w in f for w in ("الباحثين", "المتعلمين", "السير", "المرشحين", "اختبارات", "مطابقة", "التسرب", "الشكاوى", "التسجيل")) else "لا"
            role = rng.choice(["يوصي", "يقرر"]) if affects == "نعم" else "لا يمس قرارًا"
            if kind == "مساعد توليدي" and role == "يقرر":
                role = "يوصي"  # an assistant drafts or answers; it does not decide
            data = rng.choice(["عام", "مقيد", "مقيد", "سري"]) if affects == "نعم" else rng.choice(["عام", "عام", "مقيد"])
            unassessed = kind in ("وكيل", "أداة بناها موظف") and rng.random() < 0.5
            if unassessed:
                l = i = ""
            else:
                l = rng.randint(1, 3)
                i = rng.randint(2, 4) if affects == "نعم" else rng.randint(1, 2)
            owner = "" if unassessed and rng.random() < 0.6 else f"مدير الإدارة المستفيدة في {unit}"
            lvl = risk(l, i)
            ia = "لا ينطبق" if lvl == "" or lvl < 8 else rng.choice(["نعم", "لا"])
            if lvl == "":
                ia = "لا"
            last = "" if unassessed else f"{rng.choice([2024, 2025, 2025, 2026, 2026, 2026])}-{rng.randint(1, 12):02d}"
            if last > "2026-10":
                last = "2026-09"
            oversight = "" if unassessed else rng.choice(["يعتمد الموظف كل مخرج", "مراجعة عينة دورية", "لا يلزم"])
            rows.append([f"SYS-{n:02d}", unit, f, kind, origin, stage, affects, role, data, owner, l, i, lvl, ia, oversight, last])
            n += 1
    return rows


